@OptIn(ExperimentalLayoutApi::class)
@Composable
fun CreatorScreen(innerPadding: PaddingValues, onNavigate: (String) -> Unit, viewModel: CreatorViewModel) {
    val state by viewModel.state.collectAsStateWithLifecycle()
    val selected by viewModel.selectedId.collectAsStateWithLifecycle()
    val busy by viewModel.busy.collectAsStateWithLifecycle()
    val status by viewModel.status.collectAsStateWithLifecycle()
    val preview by viewModel.preview.collectAsStateWithLifecycle()
    val projects = state.workspaces.filter { it.creation != null }
    val project = projects.firstOrNull { it.id == selected }
    val plan = project?.creation
    val granted = state.permissions.any { it.capabilityId == CreationPlan.CAPABILITY && it.granted }
    var editing by remember { mutableStateOf<CreationEditTarget?>(null) }
    val edit: (CreationEditTarget) -> Unit = { viewModel.clearStatus(); editing = it }
    Surface(Modifier.fillMaxSize(), color = Retro.Background) {
        LazyColumn(Modifier.fillMaxSize().padding(innerPadding).padding(horizontal = 12.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
            item {
                Text("CREATOR / CREATIONS", color = Retro.Emerald, fontFamily = RetroMono)
                Text("Plan a story or miniseries locally. Keep characters, references, shots and audio slots together; export a production manifest for later rendering.", color = Retro.TextDim)
                FlowRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    RetroButton("New story / series", { edit(CreationEditTarget(CreationEditKind.NEW_PROJECT, "")) }, enabled = granted && !busy)
                    RetroButton("Abilities", { onNavigate(NavScreens.Abilities.route) })
                }
                if (!granted) Text("Grant Creator planning in Abilities to create, edit or export. Rendering requires a separate configured, qualified provider.", color = Retro.Amber)
                if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
                status?.let { Text(it, color = Retro.Amber) }
                Text("Creations library", color = Retro.Emerald)
                if (projects.isEmpty()) Text("No creations yet. Start a story or series; no renderer or model is needed for planning.", color = Retro.TextDim)
                FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                    projects.takeLast(30).reversed().forEach { item -> RetroButton(item.name, { viewModel.open(item.id) }, enabled = !busy, accent = if (item.id == selected) Retro.Emerald else Retro.TextDim) }
                }
            }
            if (project != null && plan != null) {
                item {
                    RetroPanel(Modifier.fillMaxWidth()) {
                        Text("${project.name} · ${plan.kind}", color = Retro.TextPrimary)
                        Text(plan.synopsis, color = Retro.TextDim)
                        Text("${plan.seasons.size} seasons · ${plan.episodes().size} episodes · ${plan.scenes().size} scenes · ${plan.shots().size} shots · ${plan.shots().sumOf { it.durationMs } / 1000.0} planned seconds", color = Retro.TextDim)
                        Text("Planning only. No images, video, voice or music have been generated by this workspace.", color = Retro.Amber)
                        if (state.activeWorkspaceId != project.id) Text("This window remains bound to ${project.name}; another project is active elsewhere.", color = Retro.Amber)
                        FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            RetroButton("Edit synopsis", { edit(CreationEditTarget(CreationEditKind.SYNOPSIS, project.id)) }, enabled = granted && !busy)
                            RetroButton("Add season", { edit(CreationEditTarget(CreationEditKind.SEASON, project.id)) }, enabled = granted && !busy)
                            RetroButton("Review production manifest", { viewModel.prepareExport(project.id) }, enabled = granted && !busy)
                            RetroButton("Project files", { viewModel.open(project.id) { onNavigate(NavScreens.Files.route) } }, enabled = !busy)
                        }
                    }
                }
                plan.seasons.forEach { season ->
                    item(key = season.id) {
                        FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            Text("${season.ordinal}. ${season.title}", color = Retro.Emerald)
                            RetroButton("Rename", { edit(CreationEditTarget(CreationEditKind.SEASON, project.id, recordId = season.id)) }, enabled = granted && !busy)
                            RetroButton("Add episode", { edit(CreationEditTarget(CreationEditKind.EPISODE, project.id, season.id)) }, enabled = granted && !busy)
                        }
                    }
                    season.episodes.forEach { episode ->
                        item(key = episode.id) {
                            FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                Text("Episode ${episode.ordinal}: ${episode.title}", color = Retro.TextPrimary)
                                RetroButton("Rename", { edit(CreationEditTarget(CreationEditKind.EPISODE, project.id, recordId = episode.id)) }, enabled = granted && !busy)
                                RetroButton("Add scene", { edit(CreationEditTarget(CreationEditKind.SCENE, project.id, episode.id)) }, enabled = granted && !busy)
                            }
                        }
                        episode.scenes.forEach { scene ->
                            item(key = scene.id) {
                                FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                    Text("Scene ${scene.ordinal}: ${scene.title}", color = Retro.TextDim)
                                    RetroButton("Rename", { edit(CreationEditTarget(CreationEditKind.SCENE, project.id, recordId = scene.id)) }, enabled = granted && !busy)
                                    RetroButton("Add shot", { edit(CreationEditTarget(CreationEditKind.SHOT, project.id, scene.id)) }, enabled = granted && !busy)
                                }
                            }
                            scene.shots.forEach { shot -> item(key = shot.id) {
                                RetroPanel(Modifier.fillMaxWidth()) {
                                    Text("Shot ${shot.ordinal} · ${shot.durationMs / 1000.0}s", color = Retro.TextPrimary)
                                    Text(shot.prompt.ifBlank { "Missing prompt — draft needs attention" }, color = Retro.TextDim)
                                    if (shot.dialogue.isNotBlank()) Text("Dialogue: ${shot.dialogue}", color = Retro.TextDim)
                                    Text("${shot.characterIds.size} characters · ${shot.assetIds.size} reference assets · ${shot.audioSlotIds.size} audio slots", color = Retro.TextDim)
                                    RetroButton("Edit shot / continuity", { edit(CreationEditTarget(CreationEditKind.SHOT, project.id, scene.id, shot.id)) }, enabled = granted && !busy)
                                }
                            } }
                        }
                    }
                }
                item { FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                    RetroButton("Add character", { edit(CreationEditTarget(CreationEditKind.CHARACTER, project.id)) }, enabled = granted && !busy)
                    RetroButton("Register asset reference", { edit(CreationEditTarget(CreationEditKind.ASSET, project.id)) }, enabled = granted && !busy)
                    RetroButton("Add voice / audio slot", { edit(CreationEditTarget(CreationEditKind.AUDIO, project.id)) }, enabled = granted && !busy)
                } }
                plan.characters.forEach { character -> item(key = character.id) {
                    RetroPanel(Modifier.fillMaxWidth()) {
                        Text("Character: ${character.name}", color = Retro.Emerald)
                        Text(character.bible.ifBlank { "Bible not written yet" }, color = Retro.TextDim)
                        Text("Reference assets: ${character.assetIds.size}", color = Retro.TextDim)
                        RetroButton("Edit character", { edit(CreationEditTarget(CreationEditKind.CHARACTER, project.id, recordId = character.id)) }, enabled = granted && !busy)
                    }
                } }
                plan.assets.forEach { asset -> item(key = asset.id) {
                    RetroPanel(Modifier.fillMaxWidth()) {
                        Text("Asset reference: ${asset.name} · ${asset.kind}", color = Retro.TextPrimary)
                        Text("${asset.sourceRef.ifBlank { "No source locator" }}\nDeclared rights: ${asset.rights}\n${asset.license.ifBlank { "License unspecified" }}", color = Retro.TextDim)
                        Text("Reference metadata only; this does not download or verify media.", color = Retro.Amber)
                        RetroButton("Edit provenance / rights", { edit(CreationEditTarget(CreationEditKind.ASSET, project.id, recordId = asset.id)) }, enabled = granted && !busy)
                    }
                } }
                plan.audioSlots.forEach { slot -> item(key = slot.id) {
                    RetroPanel(Modifier.fillMaxWidth()) {
                        Text("${slot.kind}: ${slot.name}", color = Retro.Emerald)
                        Text(slot.script.ifBlank { "Script / direction not written yet" }, color = Retro.TextDim)
                        Text("Planned slot; audio has not been synthesized.", color = Retro.Amber)
                        RetroButton("Edit audio slot", { edit(CreationEditTarget(CreationEditKind.AUDIO, project.id, recordId = slot.id)) }, enabled = granted && !busy)
                    }
                } }
            }
            item {
                Text("Renderer connections", color = Retro.Emerald)
                CreationProviders.all.forEach { Text("${it.id}: ${it.reason}", color = Retro.TextDim) }
                Spacer(Modifier.height(16.dp))
            }
        }
    }
    editing?.let { target ->
        val boundPlan = state.workspaces.firstOrNull { it.id == target.workspaceId }?.creation
        CreationEditDialog(target, boundPlan, granted && !busy, !busy, status, { editing = null }) { form -> viewModel.save(target, form) { editing = null } }
    }
    preview?.let { reviewed -> AlertDialog(onDismissRequest = viewModel::dismissExport, title = { Text("Review ${reviewed.title}") },
        text = { Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text("Production plan only: ${reviewed.manifest.jobs.size} blocked render jobs. Includes all story prompts, dialogue, character bible, asset source/rights declarations and audio slots. Sharing is explicit.")
            reviewed.manifest.checks.forEach { Text("${if (it.passed) "CHECK" else "ATTENTION"}: ${it.detail}") }
            status?.let { Text(it, color = MaterialTheme.colorScheme.error) }
            Text("SHA-256: ${reviewed.sha256}")
            Text(if (reviewed.json.length > 16_000) "JSON excerpt (complete file is shared):" else "Complete JSON:")
            Text(reviewed.json.take(16_000))
        } }, confirmButton = { TextButton(onClick = { viewModel.shareReviewed(reviewed) }, enabled = granted && !busy) { Text("Share reviewed manifest") } },
        dismissButton = { TextButton(onClick = viewModel::dismissExport) { Text("Cancel") } }) }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun CreationEditDialog(target: CreationEditTarget, plan: CreationPlan?, enabled: Boolean, canDismiss: Boolean, status: String?, onDismiss: () -> Unit, onSave: (CreationForm) -> Unit) {
    val initial = remember(target) { initialForm(target, plan) }
    var form by remember(target) { mutableStateOf(initial) }
    val kind = target.kind
    val nameNeeded = kind !in setOf(CreationEditKind.SHOT, CreationEditKind.SYNOPSIS)
    val bodyNeeded = kind in setOf(CreationEditKind.NEW_PROJECT, CreationEditKind.SYNOPSIS, CreationEditKind.SHOT, CreationEditKind.CHARACTER, CreationEditKind.ASSET, CreationEditKind.AUDIO)
    AlertDialog(onDismissRequest = { if (canDismiss) onDismiss() }, title = { Text((if (target.recordId == null) "New / add " else "Edit ") + kind.name.lowercase().replace('_', ' ')) },
        text = { Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            if (nameNeeded) OutlinedTextField(form.name, { if (it.length <= if (kind == CreationEditKind.NEW_PROJECT) 64 else 128) form = form.copy(name = it) }, label = { Text("Name / title") }, enabled = enabled, modifier = Modifier.fillMaxWidth())
            if (kind == CreationEditKind.NEW_PROJECT) FlowRow { CreationKind.entries.forEach { option -> TextButton(onClick = { form = form.copy(creationKind = option) }, enabled = enabled) { Text((if (form.creationKind == option) "● " else "") + option.name) } } }
            if (bodyNeeded) OutlinedTextField(form.body, { if (it.length <= 4000) form = form.copy(body = it) }, label = { Text(when (kind) {
                CreationEditKind.CHARACTER -> "Character bible / continuity notes"
                CreationEditKind.ASSET -> "Prompt / reference provenance"
                CreationEditKind.AUDIO -> "Voice script / audio direction"
                CreationEditKind.SHOT -> "Shot prompt"
                else -> "Synopsis / story plan"
            }) }, enabled = enabled, modifier = Modifier.fillMaxWidth().heightIn(min = 120.dp, max = 240.dp))
            if (kind == CreationEditKind.SHOT) {
                OutlinedTextField(form.seconds, { if (it.length <= 12) form = form.copy(seconds = it) }, label = { Text("Duration in seconds (1..600)") }, keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Decimal), enabled = enabled)
                OutlinedTextField(form.secondary, { if (it.length <= 4000) form = form.copy(secondary = it) }, label = { Text("Dialogue (optional)") }, enabled = enabled, modifier = Modifier.fillMaxWidth())
                Text("Characters")
                FlowRow { plan?.characters?.forEach { character -> FilterChip(selected = character.id in form.characterIds, onClick = { form = form.copy(characterIds = toggle(form.characterIds, character.id)) }, label = { Text(character.name) }, enabled = enabled) } }
                Text("Audio slots")
                FlowRow { plan?.audioSlots?.forEach { slot -> FilterChip(selected = slot.id in form.audioSlotIds, onClick = { form = form.copy(audioSlotIds = toggle(form.audioSlotIds, slot.id)) }, label = { Text(slot.name) }, enabled = enabled) } }
            }
            if (kind in setOf(CreationEditKind.SHOT, CreationEditKind.CHARACTER, CreationEditKind.AUDIO)) {
                Text(if (kind == CreationEditKind.AUDIO) "Registered audio reference (optional, one)" else "Registered reference assets")
                val eligibleAssets = plan?.assets.orEmpty().filter { kind != CreationEditKind.AUDIO || it.kind in setOf(CreationAssetKind.AUDIO, CreationAssetKind.REFERENCE) }
                FlowRow { eligibleAssets.forEach { asset -> FilterChip(selected = asset.id in form.assetIds, onClick = { form = form.copy(assetIds = if (kind == CreationEditKind.AUDIO) if (asset.id in form.assetIds) emptyList() else listOf(asset.id) else toggle(form.assetIds, asset.id)) }, label = { Text(asset.name) }, enabled = enabled) } }
                if (eligibleAssets.isEmpty()) Text(if (kind == CreationEditKind.AUDIO) "Register an AUDIO or REFERENCE asset to link this slot. No media is generated by selecting a reference." else "Register asset references in the project first. No media is generated by selecting a reference.")
            }
            if (kind == CreationEditKind.ASSET) {
                FlowRow { CreationAssetKind.entries.forEach { option -> TextButton(onClick = { form = form.copy(assetKind = option) }, enabled = enabled) { Text((if (form.assetKind == option) "● " else "") + option.name) } } }
                OutlinedTextField(form.secondary, { if (it.length <= 2048) form = form.copy(secondary = it) }, label = { Text("Source locator / provenance reference") }, enabled = enabled, modifier = Modifier.fillMaxWidth())
                Text("Author-declared rights")
                FlowRow { AssetRights.entries.forEach { option -> TextButton(onClick = { form = form.copy(rights = option) }, enabled = enabled) { Text((if (form.rights == option) "● " else "") + option.name) } } }
                OutlinedTextField(form.license, { if (it.length <= 1000) form = form.copy(license = it) }, label = { Text("License / ownership notes") }, enabled = enabled, modifier = Modifier.fillMaxWidth())
            }
            if (kind == CreationEditKind.AUDIO) FlowRow { CreationAudioKind.entries.forEach { option -> TextButton(onClick = { form = form.copy(audioKind = option) }, enabled = enabled) { Text((if (form.audioKind == option) "● " else "") + option.name) } } }
            status?.let { Text(it, color = MaterialTheme.colorScheme.error) }
        } }, confirmButton = { TextButton(onClick = { onSave(form) }, enabled = enabled && (!nameNeeded || form.name.isNotBlank()) && (kind !in setOf(CreationEditKind.NEW_PROJECT, CreationEditKind.SYNOPSIS) || form.body.isNotBlank())) { Text("Save locally") } },
        dismissButton = { TextButton(onClick = onDismiss, enabled = canDismiss) { Text("Cancel") } })
}
private fun toggle(values: List<String>, id: String) = if (id in values) values - id else values + id
private fun initialForm(target: CreationEditTarget, plan: CreationPlan?): CreationForm {
    val shot = plan?.shots()?.firstOrNull { it.id == target.recordId }
    val character = plan?.characters?.firstOrNull { it.id == target.recordId }
    val asset = plan?.assets?.firstOrNull { it.id == target.recordId }
    val audio = plan?.audioSlots?.firstOrNull { it.id == target.recordId }
    val title = plan?.seasons?.firstOrNull { it.id == target.recordId }?.title ?: plan?.episodes()?.firstOrNull { it.id == target.recordId }?.title ?: plan?.scenes()?.firstOrNull { it.id == target.recordId }?.title
    return CreationForm(name = character?.name ?: asset?.name ?: audio?.name ?: title ?: "",
        body = shot?.prompt ?: character?.bible ?: asset?.provenance?.prompt ?: audio?.script ?: if (target.kind == CreationEditKind.SYNOPSIS) plan?.synopsis.orEmpty() else "",
        secondary = shot?.dialogue ?: asset?.sourceRef ?: "", license = asset?.license.orEmpty(), creationKind = plan?.kind ?: CreationKind.STORY,
        assetKind = asset?.kind ?: CreationAssetKind.REFERENCE, audioKind = audio?.kind ?: CreationAudioKind.VOICE, rights = asset?.rights ?: AssetRights.UNKNOWN,
        seconds = shot?.let { java.math.BigDecimal(it.durationMs).divide(java.math.BigDecimal(1000)).stripTrailingZeros().toPlainString() } ?: "6",
        characterIds = shot?.characterIds.orEmpty(), assetIds = shot?.assetIds ?: character?.assetIds ?: audio?.assetId?.let { listOf(it) }.orEmpty(), audioSlotIds = shot?.audioSlotIds.orEmpty())
}
